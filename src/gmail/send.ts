/**
 * Gmail send
 * ==========
 * Sends one OUTBOUND message via the Gmail REST API (users.messages.send).
 * Sends a multipart/alternative MIME message (plain-text + HTML) so the reply
 * renders nicely in modern mail clients while remaining readable in plain-text ones.
 *
 * Threading works via two mechanisms that must both be present:
 *   - HTTP body: `threadId` field tells Gmail which thread to attach the message to.
 *   - MIME headers: `In-Reply-To` + `References` so mail clients render the
 *     thread correctly (RFC 2822 §3.6.4).
 *
 * The access token is refreshed for each send — sends are infrequent and the
 * token round-trip cost is negligible vs. the send itself.
 */

import { resolveGmailConnection } from './credentials.js';

const GMAIL_API_BASE = 'https://gmail.googleapis.com/gmail/v1';
const MIME_BOUNDARY = '----OvrtAgentBoundary';

export type SendArgs = {
  /** SupportChannelConnection.id (channelType=GMAIL), not the email address. */
  connectionId: string;
  /** Gmail thread id the reply belongs to (SupportConversation.externalConversationId). */
  externalConversationId: string;
  from: string;
  to: string;
  subject: string;
  body: string;
  /** Value of the inbound message's Message-ID header — goes into In-Reply-To. */
  inReplyToHeader: string | null;
  /** Accumulated References chain from the inbound message + its own Message-ID. */
  references: string | null;
};

export type SendResult = {
  /** Gmail message id assigned to the sent message. */
  gmailMessageId: string;
  /** Gmail thread id (should match what we passed in). */
  gmailThreadId: string;
};

/** Escape the minimum set of HTML entities needed for safe body injection. */
function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Convert the agent's plain-text reply body into an HTML email.
 * Blank lines become paragraph breaks; single newlines become <br>.
 * A branded footer is appended regardless of what the LLM produced.
 */
function buildHtmlBody(plainBody: string): string {
  const paragraphs = plainBody
    .trim()
    .split(/\n{2,}/)
    .map((para) =>
      `<p style="margin:0 0 16px 0">${escapeHtml(para.trim()).replace(/\n/g, '<br>')}</p>`,
    )
    .join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head>
<body style="margin:0;padding:0;background:#f5f5f5;font-family:Arial,Helvetica,sans-serif">
  <table width="100%" cellpadding="0" cellspacing="0" style="background:#f5f5f5;padding:32px 0">
    <tr>
      <td align="center">
        <table width="600" cellpadding="0" cellspacing="0" style="background:#ffffff;border-radius:8px;overflow:hidden;box-shadow:0 1px 4px rgba(0,0,0,0.08)">

          <!-- Body -->
          <tr>
            <td style="padding:32px 40px;color:#1a1a1a;font-size:15px;line-height:1.6">
              ${paragraphs}
            </td>
          </tr>

          <!-- Footer -->
          <tr>
            <td style="padding:20px 40px;border-top:1px solid #e8e8e8;background:#fafafa">
              <p style="margin:0;font-size:12px;color:#999999;line-height:1.5">
                This email was generated by <strong>Ovrt Support Agent</strong>.
                If you believe this was sent in error, please disregard it.
              </p>
              <a style="margin:0;font-size:12px; color: #284be9;line-height:1.5;text-decoration:none" href="https://ovrt.in">Learn more about Ovrt</a>
            </td>
          </tr>

        </table>
      </td>
    </tr>
  </table>
</body>
</html>`;
}

/**
 * Build a multipart/alternative RFC 2822 MIME message with both a plain-text
 * and HTML part. Mail clients prefer the last matching part, so HTML goes last.
 * Line endings must be CRLF per spec.
 */
function buildRawMime(args: SendArgs): string {
  const headers: [string, string][] = [
    ['From', args.from],
    ['To', args.to],
    ['Subject', args.subject],
    ['MIME-Version', '1.0'],
    ['Content-Type', `multipart/alternative; boundary="${MIME_BOUNDARY}"`],
  ];
  if (args.inReplyToHeader) headers.push(['In-Reply-To', args.inReplyToHeader]);
  if (args.references) headers.push(['References', args.references]);

  const headerBlock = headers.map(([k, v]) => `${k}: ${v}`).join('\r\n');

  const plainPart = [
    `--${MIME_BOUNDARY}`,
    'Content-Type: text/plain; charset=utf-8',
    'Content-Transfer-Encoding: 7bit',
    '',
    args.body,
  ].join('\r\n');

  const htmlPart = [
    `--${MIME_BOUNDARY}`,
    'Content-Type: text/html; charset=utf-8',
    'Content-Transfer-Encoding: 7bit',
    '',
    buildHtmlBody(args.body),
  ].join('\r\n');

  const raw = `${headerBlock}\r\n\r\n${plainPart}\r\n\r\n${htmlPart}\r\n--${MIME_BOUNDARY}--`;
  return Buffer.from(raw).toString('base64url');
}

export async function sendGmailReply(args: SendArgs): Promise<SendResult> {
  const conn = await resolveGmailConnection(args.connectionId);

  const res = await fetch(`${GMAIL_API_BASE}/users/me/messages/send`, {
    method: 'POST',
    headers: {
      authorization: `Bearer ${conn.accessToken}`,
      'content-type': 'application/json',
    },
    body: JSON.stringify({
      threadId: args.externalConversationId,
      raw: buildRawMime(args),
    }),
  });

  if (!res.ok) {
    const detail = await res.text().catch(() => '');
    throw new Error(`gmail send failed (${res.status}) for ${args.from}: ${detail}`);
  }

  const data = (await res.json()) as { id: string; threadId: string };
  return { gmailMessageId: data.id, gmailThreadId: data.threadId };
}
